import sharp from 'sharp';
import { writeFileSync } from 'fs';

// The receipt document is exported by modern-screenshot, which fetches remote
// images to inline them — but CapacitorHttp patches window.fetch in the app, so
// that fetch breaks and the whole capture fails. Embedding the images as data
// URIs means there is nothing to fetch at export time.
// Sized at 2x their on-screen box (capture runs at scale: 2) to stay crisp
// while keeping the bundle small.
const SOURCES = [
  { name: 'LOGO', file: 'assets/logo-source.png', w: 128, h: 128 },
  { name: 'SIGNATURE', file: '../public/sign/signature.png', w: 440, h: 128 },
];

let out = '// AUTO-GENERATED by make-receipt-assets.mjs — do not edit by hand.\n';
out += '// Receipt images inlined as data URIs so exporting never needs a network fetch.\n\n';

for (const { name, file, w, h } of SOURCES) {
  const buf = await sharp(file)
    .resize(w, h, { fit: 'inside', withoutEnlargement: true })
    .png({ compressionLevel: 9 })
    .toBuffer();
  out += `export const ${name} = 'data:image/png;base64,${buf.toString('base64')}';\n\n`;
  console.log(`${name}: ${(buf.length / 1024).toFixed(1)} KB`);
}

writeFileSync('src/lib/receiptAssets.js', out);
console.log('wrote src/lib/receiptAssets.js');
